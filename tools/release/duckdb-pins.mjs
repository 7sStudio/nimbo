// Writes packages/server/src/files/duckdb/pins.ts from pnpm-lock.yaml: the version of @duckdb/node-api query-sql
// is built against, and the npm integrity of it, of @duckdb/node-bindings and of each macOS and Linux platform package,
// which `sql.install` checks every download against. `--check` fails when the file is not what the lockfile says.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const lock = readFileSync(join(root, "pnpm-lock.yaml"), "utf8");
const querySql = JSON.parse(readFileSync(join(root, "packages/query-sql/package.json"), "utf8"));
const version = querySql.peerDependencies["@duckdb/node-api"];
const targets = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"];

/** The integrity the lockfile's `packages:` section gives `name@version`. */
function integrity(name) {
  const key = `  '${name}@${version}':\n    resolution: {integrity: `;
  const at = lock.indexOf(key);
  if (at === -1) throw new Error(`pnpm-lock.yaml has no resolution for ${name}@${version}`);
  return lock.slice(at + key.length, lock.indexOf("}", at)).trim();
}

const pin = (name) => ({ name, integrity: integrity(name) });
const pins = {
  version,
  common: [pin("@duckdb/node-api"), pin("@duckdb/node-bindings")],
  platform: Object.fromEntries(
    targets.map((target) => [target, pin(`@duckdb/node-bindings-${target}`)]),
  ),
};

const raw = `// Generated by tools/release/duckdb-pins.mjs from pnpm-lock.yaml: do not edit. The DuckDB binding \`sql.install\`
// installs, each package pinned to the integrity the lockfile recorded.
export const duckdbPins = ${JSON.stringify(pins, null, 2)} as const;
`;
const file = join(root, "packages/server/src/files/duckdb/pins.ts");
const text = await prettier.format(raw, {
  ...(await prettier.resolveConfig(file)),
  filepath: file,
});
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {
    // no file yet: it differs
  }
  if (current !== text) {
    console.error(
      `${file} is not what pnpm-lock.yaml says: run node tools/release/duckdb-pins.mjs`,
    );
    process.exit(1);
  }
} else {
  writeFileSync(file, text);
}
