// The Homebrew formula of a release (Formula/nimbo.rb of the tap 7sStudio/homebrew-nimbo), generated from its
// manifest: the tarball for the user's platform, unpacked whole into libexec with the launcher linked into bin. The
// `install-method` file tells the CLI that Homebrew owns this install, so `nimbo upgrade` defers to `brew upgrade`.
//
//   node tools/release/homebrew/formula.mjs <manifest.json> [--base <url of the release's files>] > nimbo.rb
import { readFileSync } from "node:fs";
import { parseArgs } from "node:util";

const ruby = (text) => JSON.stringify(text);

/** The formula's text for `manifest`; the tarballs are fetched from `base` (the release's download folder). */
export function formula(
  manifest,
  config,
  base = `${config.releases}/download/v${manifest.version}`,
) {
  const className = manifest.name.charAt(0).toUpperCase() + manifest.name.slice(1);
  const artefact = (target, cpu) => {
    const found = manifest.targets[target];
    if (found === undefined) return [];
    return [
      `    ${cpu} do`,
      `      url ${ruby(`${base}/${found.file}`)}`,
      `      sha256 ${ruby(found.sha256)}`,
      "    end",
    ];
  };
  const platform = (os, block) => {
    const lines = [...artefact(`${os}-arm64`, "on_arm"), ...artefact(`${os}-x64`, "on_intel")];
    return lines.length === 0 ? "" : `\n  ${block} do\n${lines.join("\n")}\n  end\n`;
  };
  return `# Generated by tools/release/homebrew/formula.mjs from the release's manifest.json: do not edit.
# ${config.copyright}. Licensed under ${config.license}.
class ${className} < Formula
  desc "Local JavaScript and TypeScript notebooks with a daemon, a CLI and an MCP server"
  homepage ${ruby(config.releases.replace(/\/releases$/u, ""))}
  license ${ruby(config.license)}
${platform("darwin", "on_macos")}${platform("linux", "on_linux")}
  def install
    libexec.install Dir["*"]
    (libexec/"install-method").write "homebrew\\n"
    bin.install_symlink libexec/"bin/${manifest.name}"
  end

  def caveats
    <<~EOS
      Register the MCP server with your agents:
        ${manifest.name} mcp install
      SQL output queries from the CLI and agents need DuckDB (about 40 MB):
        ${manifest.name} sql install
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/${manifest.name} --version")
  end
end
`;
}

if (import.meta.main) {
  const { values, positionals } = parseArgs({
    options: { base: { type: "string" } },
    allowPositionals: true,
  });
  const manifest = JSON.parse(readFileSync(positionals[0] ?? "manifest.json", "utf8"));
  const config = JSON.parse(readFileSync(new URL("../config.json", import.meta.url), "utf8"));
  process.stdout.write(formula(manifest, config, values.base));
}
