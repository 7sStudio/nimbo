/** `command` with `args` in words: its variant's when there is one, else `title(command)`. */
export function labelOf(
  command: string,
  args: Args | undefined,
  title: (id: string) => string,
): string {
  const same = JSON.stringify(args ?? {});
  const variant = variants.find(
    (each) => each.command === command && JSON.stringify(each.args) === same,
  );
  return variant?.title ?? title(command);
}

