import fc from "fast-check";
import { expect, it } from "vitest";

import type { DocumentCell, NotebookDocument } from "../format/schema.js";
import type { CellType } from "../model/cell.js";
import { diffNotebooks } from "./notebookDiff.js";

type Spec = { id: string; type?: CellType; source: string; meta?: Record<string, unknown> };

const cell = ({ id, type = "server", source, meta = {} }: Spec): DocumentCell => ({
  id,
  type,
  source,
  meta,
  extra: {},
});
const doc = (cells: Spec[], top: Partial<NotebookDocument> = {}): NotebookDocument => ({
  version: 1,
  cells: cells.map(cell),
  extra: {},
  ...top,
});
const shape = (before: NotebookDocument | null, after: NotebookDocument | null) =>
  diffNotebooks(before, after).rows.map((row) => [
    row.status,
    row.before?.id ?? null,
    row.after?.id ?? null,
    ...(row.moved ? ["moved"] : []),
  ]);

it("matches cells by id and reads a source edit as modified, with its hunks", () => {
  const before = doc([
    { id: "c_a", source: "const a = 1;\nconst b = 2;" },
    { id: "c_b", source: "b" },
  ]);
  const after = doc([
    { id: "c_a", source: "const a = 1;\nconst b = 3;" },
    { id: "c_b", source: "b" },
  ]);
  const diff = diffNotebooks(before, after);
  expect(shape(before, after)).toEqual([
    ["modified", "c_a", "c_a"],
    ["unchanged", "c_b", "c_b"],
  ]);
  expect(diff.rows[0]?.changes.source).toMatchObject({ added: 1, removed: 1 });
  expect(diff.stats).toEqual({ added: 0, removed: 0, modified: 1, moved: 0, unchanged: 1 });
});

it("pairs cells whose ids were regenerated by identical source, then by similar source of one type", () => {
  const before = doc([
    { id: "c_old1", source: "same text" },
    { id: "c_old2", source: "a\nb\nc\nd\ne" },
    { id: "c_old3", type: "markdown", source: "a\nb\nc\nd\ne" },
  ]);
  const after = doc([
    { id: "c_new1", source: "same text" },
    { id: "c_new2", source: "a\nb\nc\nd\nE" },
    { id: "c_new3", type: "client", source: "nothing alike" },
  ]);
  expect(shape(before, after)).toEqual([
    ["unchanged", "c_old1", "c_new1"],
    ["modified", "c_old2", "c_new2"],
    ["removed", "c_old3", null],
    ["added", null, "c_new3"],
  ]);
});

it("marks the cells that left their order as moved, and keeps the longest run in place", () => {
  const ids = ["c_1", "c_2", "c_3", "c_4"];
  const before = doc(ids.map((id) => ({ id, source: id })));
  const after = doc(["c_4", "c_1", "c_2", "c_3"].map((id) => ({ id, source: id })));
  const diff = diffNotebooks(before, after);
  expect(shape(before, after)).toEqual([
    ["unchanged", "c_4", "c_4", "moved"],
    ["unchanged", "c_1", "c_1"],
    ["unchanged", "c_2", "c_2"],
    ["unchanged", "c_3", "c_3"],
  ]);
  expect(diff.rows[0]?.moved).toEqual({ from: 3, to: 0 });
  expect(diff.stats.moved).toBe(1);
});

it("places a removed cell after the nearest earlier cell that survived, or first", () => {
  const before = doc([
    { id: "c_x", source: "x" },
    { id: "c_a", source: "a" },
    { id: "c_y", source: "y" },
    { id: "c_b", source: "b" },
  ]);
  const after = doc([
    { id: "c_a", source: "a" },
    { id: "c_b", source: "b" },
  ]);
  expect(shape(before, after)).toEqual([
    ["removed", "c_x", null],
    ["unchanged", "c_a", "c_a"],
    ["removed", "c_y", null],
    ["unchanged", "c_b", "c_b"],
  ]);
});

it("reads a type change and a meta-only change, lastEdit among the meta", () => {
  const edit = { by: "agent", at: "2026-11-15T10:00:00.000Z" };
  const before = doc([
    { id: "c_a", source: "x" },
    { id: "c_b", source: "y", meta: { collapsed: true } },
  ]);
  const after = doc([
    { id: "c_a", type: "client", source: "x" },
    { id: "c_b", source: "y", meta: { lastEdit: edit } },
  ]);
  const [typed, meta] = diffNotebooks(before, after).rows;
  expect(typed?.changes).toEqual({ type: { from: "server", to: "client" } });
  expect(meta?.status).toBe("modified");
  expect(meta?.changes).toEqual({
    meta: [
      { key: "collapsed", from: true },
      { key: "lastEdit", to: edit },
    ],
  });
});

it("reads meta with its keys in another order as unchanged", () => {
  const before = doc([{ id: "c_a", source: "x", meta: { outputQuery: { a: 1, b: 2 } } }]);
  const after = doc([{ id: "c_a", source: "x", meta: { outputQuery: { b: 2, a: 1 } } }]);
  expect(diffNotebooks(before, after).rows[0]?.status).toBe("unchanged");
});

it("reads an added or a deleted notebook, and an empty one", () => {
  const one = doc([{ id: "c_a", source: "one\ntwo" }]);
  expect(diffNotebooks(null, one).rows[0]).toMatchObject({
    status: "added",
    changes: { source: { added: 2, removed: 0 } },
  });
  expect(diffNotebooks(one, null).rows[0]).toMatchObject({
    status: "removed",
    changes: { source: { added: 0, removed: 2 } },
  });
  expect(diffNotebooks(doc([]), doc([]))).toEqual({
    header: [],
    rows: [],
    stats: { added: 0, removed: 0, modified: 0, moved: 0, unchanged: 0 },
  });
});

it("lists the header's changes: jsnb, version and unknown top-level keys", () => {
  const before = doc([], { extra: { tags: ["a"] } });
  const after = doc([], { jsnb: "0.1.0", extra: {} });
  expect(diffNotebooks(before, after).header).toEqual([
    { key: "jsnb", to: "0.1.0" },
    { key: "tags", from: ["a"] },
  ]);
});

it("matches every cell once and finds nothing in a notebook against itself", () => {
  const cells = fc.array(
    fc.record({
      id: fc.constantFrom("c_1", "c_2", "c_3", "c_4", "c_5", "c_6"),
      type: fc.constantFrom<CellType>("server", "client", "markdown"),
      source: fc
        .array(fc.constantFrom("a", "b", "c", ""), { maxLength: 5 })
        .map((l) => l.join("\n")),
    }),
    { maxLength: 6 },
  );
  const unique = cells.map((list) => [...new Map(list.map((c) => [c.id, c])).values()]);
  fc.assert(
    fc.property(unique, unique, (left, right) => {
      const a = doc(left);
      const b = doc(right);
      const rows = diffNotebooks(a, b).rows;
      const olds = rows.flatMap((row) => (row.before ? [row.before.index] : [])).sort();
      const news = rows.flatMap((row) => (row.after ? [row.after.index] : []));
      expect(olds).toEqual(left.map((_, at) => at));
      expect(news).toEqual(right.map((_, at) => at));
      const self = diffNotebooks(a, a);
      expect(self.rows.every((row) => row.status === "unchanged" && !row.moved)).toBe(true);
      expect(self.header).toEqual([]);
    }),
  );
});

it("marks a cell whose saved run changed, and leaves one whose run only took another time", () => {
  const run = (value: number, startedAt = "2026-11-15T10:00:00Z", durationMs = 5) => ({
    status: "ok" as const,
    startedAt,
    durationMs,
    outputs: [{ kind: "value" as const, json: value, repr: String(value), truncated: false }],
  });
  const cells = [
    { id: "c_a", source: "a" },
    { id: "c_b", source: "b" },
    { id: "c_c", source: "c" },
  ];
  const before = doc(cells, { outputs: { c_a: run(1), c_b: run(2) } });
  const after = doc(cells, {
    outputs: { c_a: run(5), c_b: run(2, "2026-11-15T11:00:00Z", 9), c_c: run(3) },
  });
  const diff = diffNotebooks(before, after);
  expect(shape(before, after)).toEqual([
    ["modified", "c_a", "c_a"],
    ["unchanged", "c_b", "c_b"],
    ["modified", "c_c", "c_c"],
  ]);
  expect(diff.rows[0]?.changes.outputs).toMatchObject({
    before: "ok",
    after: "ok",
    comparison: { same: false, value: { changes: [{ kind: "changed", path: "$" }] } },
  });
  expect(diff.rows[2]?.changes.outputs).toMatchObject({ after: "ok" });
  expect(diff.rows[2]?.changes.outputs?.before).toBeUndefined();
  expect(diff.rows[0]?.changes.source).toBeUndefined();
});
